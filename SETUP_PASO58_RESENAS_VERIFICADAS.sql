alter table public.product_reviews add column if not exists verified_purchase boolean not null default true;
alter table public.product_reviews add column if not exists status text not null default 'pending';
alter table public.product_reviews add column if not exists featured boolean not null default false;
alter table public.product_reviews add column if not exists admin_note text;
alter table public.product_reviews add column if not exists moderated_at timestamptz;
alter table public.product_reviews add column if not exists moderated_by text;
alter table public.product_reviews add column if not exists published_at timestamptz;
alter table public.product_reviews add column if not exists updated_at timestamptz not null default now();

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'product_reviews_order_product_unique'
      and conrelid = 'public.product_reviews'::regclass
  ) then
    alter table public.product_reviews
      add constraint product_reviews_order_product_unique unique (order_id, product_id);
  end if;
end;
$$;

create index if not exists product_reviews_public_idx
  on public.product_reviews (product_id, status, featured desc, published_at desc, created_at desc);

create index if not exists product_reviews_admin_idx
  on public.product_reviews (status, created_at desc);

alter table public.product_reviews enable row level security;

