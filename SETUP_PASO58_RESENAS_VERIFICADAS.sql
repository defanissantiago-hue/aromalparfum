create table if not exists public.product_reviews (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  order_id bigint not null references public.orders(id) on delete cascade,
  order_item_id bigint references public.order_items(id) on delete set null,
  purchase_type text not null default 'product',
  reviewer_display_name text not null default 'Cliente verificado',
  rating smallint not null,
  title text,
  body text not null,
  verified_purchase boolean not null default true,
  status text not null default 'pending',
  featured boolean not null default false,
  admin_note text,
  created_at timestamptz not null default now(),
  moderated_at timestamptz,
  moderated_by text,
  published_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint product_reviews_rating_check check (rating between 1 and 5),
  constraint product_reviews_status_check check (status in ('pending','approved','rejected')),
  constraint product_reviews_order_product_unique unique (order_id, product_id)
);

